'''
plots a trajectory in joint and cartesian space

usage: python plot_trajectory.py <path/to/trajectory.csv>
'''
import argparse
import matplotlib.pyplot as plt
import numpy as np
from experiment_assets import load_trajectory

###################################
def parse_args():
###################################
    '''
    Parse arguements and determine whether to list existing trajectory functions
    or run one of them
    '''
    parser = argparse.ArgumentParser()
    parser.add_argument('traj' , help='trajectory filepath generated by create_trajectories.py' )

    args = parser.parse_args()    

    return args

def main():
    args = parse_args()
    traj = load_trajectory(args.traj)
    plt.plot(traj.time, traj.joint_position)
    plt.legend(['joint 1', 'joint 2', 'joint 3'])
    plt.title(traj.source.name+" joint positions")
    plt.xlabel("time (s)")
    plt.ylabel("position (rad)")
    plt.show()

    fig = plt.figure()
    ax = fig.add_subplot(projection='3d')

    ax.plot(traj.position[:,0], traj.position[:,1], traj.position[:,2], color='purple', lw=2)

    # Set descriptive axis labels
    ax.set_title(traj.source.name+" cartesian position")
    ax.set_xlabel('X (m)')
    ax.set_ylabel('Y (m)')
    ax.set_zlabel('Z (m)')
    plt.show()
        

if __name__ == "__main__":
    main()